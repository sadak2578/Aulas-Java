package AulasWhile;

// Contando de 1 a 100 com while
public class exercicio1_WHILE {

	public static void main(String[] args) {
		System.out.println("===========================");
		System.out.println("Imprimindo de 1 a 100");
		System.out.println("===========================");
		int contador = 1;
		
		while(contador <= 100) {
			System.out.println("Contando.. " + contador);
			contador++;
			
		}
	}

}

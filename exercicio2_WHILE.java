package AulasWhile;

/*
 Imprimir números pares utilizando o While números pares entre 0 e 50
 * */

public class exercicio2_WHILE {

	public static void main(String[] args) {
		int num = 0;
		while (num <= 50) {
			
			System.out.println("Os números pares de 0 a 50 são: " + num);
			num += 2;
			
		}

	}

}
